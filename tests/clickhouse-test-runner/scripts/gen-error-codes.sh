#!/usr/bin/env bash
# Generates clickhouse_test_runner/errorcodes.py from src/Common/ErrorCodes.cpp of a ClickHouse
# checkout. fetch-upstream.sh runs it after each checkout, so the error names of the test hints always
# match the tests. It needs only bash and sed.
#
# Usage: scripts/gen-error-codes.sh [<ClickHouse checkout>]
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUNNER_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
checkout="${1:-${UPSTREAM_CLICKHOUSE_DIR:-${RUNNER_DIR}/.upstream/ClickHouse}}"
src_file="${checkout}/src/Common/ErrorCodes.cpp"

if [[ ! -f "${src_file}" ]]; then
  echo "Error: ${src_file} not found. Run scripts/fetch-upstream.sh first." >&2
  exit 1
fi
ref="$(cat "${checkout}/.upstream-ref" 2>/dev/null || git -C "${checkout}" rev-parse HEAD)"

out="${RUNNER_DIR}/clickhouse_test_runner/errorcodes.py"
{
  echo "# Code generated by scripts/gen-error-codes.sh from ClickHouse ${ref}; DO NOT EDIT."
  echo '"""The error names of src/Common/ErrorCodes.cpp and their codes. Test hints can name an error instead of'
  echo 'giving its code."""'
  echo
  echo "ERROR_CODES = {"
  sed -n 's/^ *M(\([0-9][0-9]*\), *\([A-Z0-9_][A-Z0-9_]*\)).*/    "\2": \1,/p' "${src_file}"
  echo "}"
  echo
  echo "ERROR_NAMES = {code: name for name, code in ERROR_CODES.items()}"
} > "${out}"
echo "Wrote $(grep -c '^    "' "${out}") error codes from ${ref} to ${out}" >&2
